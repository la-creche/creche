"""A fake `uv`, a fake `curl` and a real tarball, for the per-server build.

`handover_executor_fixtures.FakeRun` records children and scripts answers.
The per-server build needs more than an answer: `uv venv` must leave a
`bin/python`, `uv pip compile` must leave a lock, and `curl` must leave a
file whose BYTES the build then hashes. A fake that only recorded the argv
would make "a lock whose hash does not match" untestable, because nothing
would have a hash.

So this fake DOES what each command does, minimally, and the test controls
what it produces. Nothing here runs `uv`, `curl` or `runuser`.
"""

from __future__ import annotations

import hashlib
import io
import tarfile
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from handover.executor.host import Command
from handover.executor.host import Result as RunResult
from handover.mcpserver import ServerFile, parse_server

